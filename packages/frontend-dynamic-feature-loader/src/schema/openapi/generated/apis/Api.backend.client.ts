/**
 * A client for use in the backend. The base URL is resolved through the
 * discovery service, and a plugin request token is requested from the auth
 * service unless one is passed in the request options.
 *
 * @public
 */
export class DefaultApiBackendClient {
  private readonly discovery: DiscoveryApi;
  private readonly auth: AuthApi;
  private readonly fetchApi: FetchApi;

  constructor(options: {
    discovery: { getBaseUrl(pluginId: string): Promise<string> };
    auth: AuthApi;
    fetchApi?: { fetch: typeof fetch };
  }) {
    this.discovery = options.discovery;
    this.auth = options.auth;
    this.fetchApi = options.fetchApi || { fetch };
  }

  /**
   * Get the Module Federation remote definitions.
   */
  public async getRemotes(
    // @ts-ignore
    request: GetRemotes,
    options?: BackendRequestOptions,
  ): Promise<TypedResponse<Array<Remote>>> {
    const baseUrl = await this.discovery.getBaseUrl(pluginId);

    const token =
      options?.token ??
      (
        await this.auth.getPluginRequestToken({
          onBehalfOf:
            options?.credentials ??
            (await this.auth.getOwnServiceCredentials()),
          targetPluginId: pluginId,
        })
      ).token;
    const uriTemplate = `/remotes`;

    const uri = parser.parse(uriTemplate).expand({});

    const init: RequestInit = {
      headers: {
        'Content-Type': 'application/json',
        ...(token && { Authorization: `Bearer ${token}` }),
      },
      method: 'GET',
    };

    return await this.fetchApi.fetch(`${baseUrl}${uri}`, init);
  }
}
