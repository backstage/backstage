import { RuleTester } from './testUtils';

const rule = require('../../config/rules/notice');

const VALID_HEADER = `/*
 * Copyright 2024 The Backstage Authors
 *
 * Licensed under the Apache License, Version 2.0 (the "License");
 * you may not use this file except in compliance with the License.
 * You may obtain a copy of the License at
 *
 *     http://www.apache.org/licenses/LICENSE-2.0
 *
 * Unless required by applicable law or agreed to in writing, software
 * distributed under the License is distributed on an "AS IS" BASIS,
 * WITHOUT WARRANTIES OR CONDITIONS OF ANY KIND, either express or implied.
 * See the License for the specific language governing permissions and
 * limitations under the License.
 */`;

const CURRENT_YEAR_HEADER = VALID_HEADER.replace(
  '2024',
  String(new Date().getFullYear()),
);

const ruleTester = new RuleTester({
  languageOptions: { sourceType: 'module' },
});

ruleTester.run('notice', rule, {
  valid: [
    {
      code: `${VALID_HEADER}\n\nexport const x = 1;`,
    },
    {
      // Different year is fine
      code: `${VALID_HEADER.replace('2024', '2020')}\n\nexport const x = 1;`,
    },
    {
      // Shebang before header is fine
      code: `#!/usr/bin/env node\n${VALID_HEADER}\n\nexport const x = 1;`,
    },
  ],
  invalid: [
    {
      code: `export const x = 1;`,
      output: `${CURRENT_YEAR_HEADER}\n\nexport const x = 1;`,
      errors: [{ message: 'Missing or incorrect Apache 2.0 copyright header' }],
    },
    {
      // A license-like leading comment is replaced
      code: `/*\n * Copyright 2019 Some Other Project\n * Licensed under MIT\n */\nexport const x = 1;`,
      output: `${CURRENT_YEAR_HEADER}\n\nexport const x = 1;`,
      errors: [{ message: 'Missing or incorrect Apache 2.0 copyright header' }],
    },
    {
      // A meaningful leading comment is kept and the header inserted in front
      code: `/**\n * @jest-environment jsdom\n */\nexport const x = 1;`,
      output: `${CURRENT_YEAR_HEADER}\n\n/**\n * @jest-environment jsdom\n */\nexport const x = 1;`,
      errors: [{ message: 'Missing or incorrect Apache 2.0 copyright header' }],
    },
    {
      // An empty line comment is a placeholder and is replaced
      code: `//\n\n// THIS IS AN AUTOGENERATED FILE.\nexport const x = 1;`,
      output: `${CURRENT_YEAR_HEADER}\n\n// THIS IS AN AUTOGENERATED FILE.\nexport const x = 1;`,
      errors: [{ message: 'Missing or incorrect Apache 2.0 copyright header' }],
    },
    {
      // A placeholder before a valid header is removed
      code: `//\n${VALID_HEADER}\n\nexport const x = 1;`,
      output: `${VALID_HEADER}\n\nexport const x = 1;`,
      errors: [{ message: 'Missing or incorrect Apache 2.0 copyright header' }],
    },
    {
      // A placeholder and another license header after it are both replaced
      code: `//\n/*\n * Copyright 2019 Some Other Project\n */\nexport const x = 1;`,
      output: `${CURRENT_YEAR_HEADER}\n\nexport const x = 1;`,
      errors: [{ message: 'Missing or incorrect Apache 2.0 copyright header' }],
    },
    {
      // Only the first of several empty line comments is the placeholder
      code: `//\n//\n\n// THIS IS AN AUTOGENERATED FILE.\nexport const x = 1;`,
      output: `${CURRENT_YEAR_HEADER}\n\n//\n\n// THIS IS AN AUTOGENERATED FILE.\nexport const x = 1;`,
      errors: [{ message: 'Missing or incorrect Apache 2.0 copyright header' }],
    },
    {
      // An empty line that starts a block of line comments is kept
      code: `//\n// Module overview\n//\nexport const x = 1;`,
      output: `${CURRENT_YEAR_HEADER}\n\n//\n// Module overview\n//\nexport const x = 1;`,
      errors: [{ message: 'Missing or incorrect Apache 2.0 copyright header' }],
    },
    {
      // A non-empty line comment is kept
      code: `// @ts-check\nexport const x = 1;`,
      output: `${CURRENT_YEAR_HEADER}\n\n// @ts-check\nexport const x = 1;`,
      errors: [{ message: 'Missing or incorrect Apache 2.0 copyright header' }],
    },
    {
      code: `/* eslint-disable-next-line no-console */\nexport const x = 1;`,
      output: `${CURRENT_YEAR_HEADER}\n\n/* eslint-disable-next-line no-console */\nexport const x = 1;`,
      errors: [{ message: 'Missing or incorrect Apache 2.0 copyright header' }],
    },
  ],
});
