import { overrideTargetPaths } from '@backstage/cli-common/testUtils';
import { PackageGraph, YarnLockfile } from '@backstage/cli-node';
import {
  detectPackageManager,
  PackageManager,
} from '@backstage/cli-node/alpha';
import info from './info';

jest.mock('@backstage/cli-node/alpha', () => ({
  ...jest.requireActual('@backstage/cli-node/alpha'),
  detectPackageManager: jest.fn(),
}));

const lockfileContents = `# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.
# yarn lockfile v1

"@backstage/core@^1.0.5":
  version "1.0.6"

"@backstage/theme@^1.0.0":
  version "1.0.0"

"@backstage/theme@^2.0.0":
  version "2.0.0"

"@backstage/local@workspace:packages/local":
  version "0.0.0-use.local"

"my-local-plugin@workspace:plugins/my-local-plugin":
  version "0.0.0-use.local"

"my-local-lib@workspace:packages/my-local-lib":
  version "0.0.0-use.local"

"lodash@^4.17.21":
  version "4.17.21"
`;

function mockPackageManager(
  name: string,
  version: string,
  loadLockfile = async () => YarnLockfile.parse(lockfileContents),
) {
  jest.mocked(detectPackageManager).mockResolvedValue({
    name: () => name,
    version: async () => version,
    lockfileName: () => (name === 'yarn' ? 'yarn.lock' : 'pnpm-lock.yaml'),
    loadLockfile,
  } as Partial<PackageManager> as PackageManager);
}

const commandInfo = { usage: 'backstage-cli info', name: 'info' };

describe('info', () => {
  overrideTargetPaths('/nonexistent-target-root');

  let logs: string[];

  beforeEach(() => {
    logs = [];
    // None of the workspace packages are resolvable from the target root, as
    // is the case for packages that nothing depends on in a pnpm workspace
    jest.spyOn(PackageGraph, 'listTargetPackages').mockResolvedValue([
      {
        dir: '/nonexistent-target-root/packages/local',
        packageJson: { name: '@backstage/local', version: '0.3.0' },
      },
      {
        dir: '/nonexistent-target-root/plugins/my-local-plugin',
        packageJson: {
          name: 'my-local-plugin',
          version: '1.2.0',
          backstage: { role: 'frontend-plugin' },
        },
      },
      {
        dir: '/nonexistent-target-root/packages/my-local-lib',
        packageJson: { name: 'my-local-lib', version: '2.0.0' },
      },
    ]);
  });

  afterEach(() => {
    jest.restoreAllMocks();
  });

  // The command never resolves, so we wait for its output instead
  function runForJsonOutput(args: string[]): Promise<any> {
    return new Promise(resolve => {
      jest.spyOn(process.stdout, 'write').mockImplementation(chunk => {
        resolve(JSON.parse(String(chunk)));
        return true;
      });
      info({ args, info: commandInfo });
    });
  }

  function runForTextOutput(args: string[]): Promise<string[]> {
    return new Promise(resolve => {
      jest.spyOn(console, 'log').mockImplementation((...logArgs) => {
        logs.push(logArgs.join(' '));
        // Everything after the first line is written synchronously
        if (logArgs[0]?.startsWith('OS:')) {
          setImmediate(() => resolve(logs));
        }
      });
      info({ args, info: commandInfo });
    });
  }

  it('reports the detected package manager, keeping the yarn field for Yarn', async () => {
    mockPackageManager('yarn', '4.1.0');

    const output = await runForJsonOutput(['--format', 'json']);
    expect(output.system).toEqual(
      expect.objectContaining({
        node: process.version,
        yarn: '4.1.0',
        packageManager: { name: 'yarn', version: '4.1.0' },
        backstage: 'N/A',
      }),
    );
    expect(output.dependencies).toEqual({
      '@backstage/core': [{ version: '1.0.6' }],
      '@backstage/theme': [{ version: '1.0.0' }, { version: '2.0.0' }],
    });
    // Local packages with a backstage field are listed without being
    // resolvable from the root, while other local packages are left out
    expect(output.local).toEqual({
      '@backstage/local': [{ version: '0.3.0' }],
      'my-local-plugin': [{ version: '1.2.0' }],
    });

    const textLogs = await runForTextOutput([]);
    expect(textLogs).toEqual(
      expect.arrayContaining([
        `node: ${process.version}`,
        'yarn: 4.1.0',
        'backstage:   N/A',
        'Dependencies:',
        '  @backstage/core  1.0.6',
        '  @backstage/theme 1.0.0, 2.0.0',
        'Local:',
        '  @backstage/local 0.3.0',
        '  my-local-plugin  1.2.0',
      ]),
    );
  });

  it('omits the yarn field for other package managers', async () => {
    mockPackageManager('pnpm', '12.7.0');

    const output = await runForJsonOutput(['--format', 'json']);
    expect(output.system).not.toHaveProperty('yarn');
    expect(output.system.packageManager).toEqual({
      name: 'pnpm',
      version: '12.7.0',
    });

    const textLogs = await runForTextOutput([]);
    expect(textLogs).toContain('pnpm: 12.7.0');
  });

  it('reports without installed versions when the lockfile cannot be read', async () => {
    const warn = jest.spyOn(console, 'warn').mockImplementation(() => {});
    mockPackageManager('yarn', '4.1.0', async () => {
      throw new Error('ENOENT: no such file or directory');
    });

    const output = await runForJsonOutput(['--format', 'json']);
    expect(output.dependencies).toEqual({});
    expect(output.local).toEqual({
      '@backstage/local': [{ version: '0.3.0' }],
    });
    expect(output.system.packageManager).toEqual({
      name: 'yarn',
      version: '4.1.0',
    });
    expect(warn).toHaveBeenCalledWith(
      expect.stringContaining(
        'Failed to read yarn.lock, installed package versions are not listed',
      ),
    );
  });
});
