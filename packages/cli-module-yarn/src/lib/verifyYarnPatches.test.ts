  it('isolates concurrent configuration environments and preserves async mutations', async () => {
    const repositoryContent = (patchFolder: string) => ({
      'package.json': packageJson({ name: 'root' }),
      '.yarnrc.yml': 'patchFolder: ${PATCH_ROOT}\n',
      [patchFolder]: {
        'orphaned.patch': 'patch',
      },
      'yarn.lock': LOCKFILE_HEADER,
    });
    concurrentMockDirA.setContent(repositoryContent('first-patches'));
    concurrentMockDirB.setContent(repositoryContent('second-patches'));

    const originalProcessEnv = process.env;
    const mutationKey = 'PATCH_HEALTH_ASYNC_MUTATION';
    const previousMutation = process.env[mutationKey];
    delete process.env[mutationKey];
    const firstEnv = { ...process.env, PATCH_ROOT: 'first-patches' };
    const secondEnv = { ...process.env, PATCH_ROOT: 'second-patches' };
    const originalFind = Configuration.find.bind(Configuration);
    let configurationCalls = 0;
    let markFirstCallEntered = () => {};
    const firstCallEntered = new Promise<void>(resolve => {
      markFirstCallEntered = resolve;
    });
    let markSecondCallEntered = () => {};
    const secondCallEntered = new Promise<void>(resolve => {
      markSecondCallEntered = resolve;
    });
    const configurationSpy = jest
      .spyOn(Configuration, 'find')
      .mockImplementation(async (...args) => {
        configurationCalls += 1;
        if (configurationCalls === 1) {
          markFirstCallEntered();
          await Promise.race([
            secondCallEntered,
            new Promise<void>(resolve => setTimeout(resolve, 50)),
          ]);
        } else if (configurationCalls === 2) {
          markSecondCallEntered();
        }
        return originalFind(...args);
      });

    try {
      const firstVerification = verifyYarnPatches({
        rootDir: concurrentMockDirA.path,
        env: firstEnv,
      });
      await firstCallEntered;
      process.env[mutationKey] = 'changed-during-verification';
      const secondVerification = verifyYarnPatches({
        rootDir: concurrentMockDirB.path,
        env: secondEnv,
      });

      await expect(
        Promise.all([firstVerification, secondVerification]),
      ).resolves.toEqual([
        {
          patchCount: 0,
          backstageCheck: 'skipped',
          errors: [
            {
              kind: 'orphaned-patch-file',
              message:
                "Patch file 'first-patches/orphaned.patch' is not referenced by any manifest",
              location: 'first-patches/orphaned.patch',
            },
          ],
        },
        {
          patchCount: 0,
          backstageCheck: 'skipped',
          errors: [
            {
              kind: 'orphaned-patch-file',
              message:
                "Patch file 'second-patches/orphaned.patch' is not referenced by any manifest",
              location: 'second-patches/orphaned.patch',
            },
          ],
        },
      ]);
      expect(process.env).toBe(originalProcessEnv);
      expect(process.env[mutationKey]).toBe('changed-during-verification');
    } finally {
      configurationSpy.mockRestore();
      process.env = originalProcessEnv;
      if (previousMutation === undefined) {
        delete process.env[mutationKey];
      } else {
        process.env[mutationKey] = previousMutation;
      }
    }
  });

